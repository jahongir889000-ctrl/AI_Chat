const MEDICAL =
  /тонометр|глюкометр|ингалятор|небулайзер|бинт|медтех|медицин|товар|каталог|доставк|заказ|полоск|расходник|термометр|стетоскоп|ортез|корсет|кислород|глюкоз|манжет/i;

const OFF_TOPIC =
  /врач|приём|прием|запис|анализ|диагноз|лечен|таблетк|дозиров|страхов|полис|операци|беремен|болит/i;

export function getLocalAgentReply(userText) {
  const phone = getMedCenterPhone();
  const trimmed = (userText ?? '').trim();
  const redirect = `Этот вопрос лучше обсудить с администратором медцентра. Позвоните: ${phone}. Я консультирую только по медицинским товарам.`;

  if (!trimmed) return redirect;

  if (/привет|здравств|добр(ый|ое|ая)/i.test(trimmed)) {
    return `Здравствуйте! Спросите о медтоварах: тонометры, глюкометры, ингаляторы, расходники. По записи к врачу и услугам клиники звоните: ${phone}.`;
  }

  if (/помощ|help|что умееш|что ты/i.test(trimmed)) {
    return `Отвечаю по медицинским товарам: назначение, комплектация, заказ и доставка. Вопросы о приёме врачей и анализах — по телефону ${phone}.`;
  }

  if (OFF_TOPIC.test(trimmed) && !MEDICAL.test(trimmed)) {
    return redirect;
  }

  const item = CATALOG.find((p) => p.keys.test(trimmed));
  if (item) {
    return `${item.name} (${item.category}): ${item.hint} Если нужна другая модель — опишите задачу. По услугам клиники: ${phone}.`;
  }

  if (MEDICAL.test(trimmed) || /доставк|заказ|налич/i.test(trimmed)) {
    const list = CATALOG.map((p) => p.name).join('; ');
    return `В каталоге сейчас: ${list}. Напишите название или тип изделия — подскажу характеристики. По записи к врачу звоните: ${phone}.`;
  }

  return redirect;
}
